// Writes src/test/slowFiles.json: the test files the fast tier leaves out.
//
//   npx vitest run --reporter=json --outputFile=report.json
//   node scripts/slow-files.mjs report.json [thresholdSeconds=15]
//
// A file is slow when its tests add up to the threshold in the report. The
// list is a speed hint, not a fence: a heavy file missing from it only makes
// `npm run test:fast` slower, and the full suite (`npm test`, verify.sh) runs
// everything regardless. Regenerate it when a page test grows heavy.
import { readFileSync, writeFileSync } from 'node:fs';
import { relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const BACKSLASH = String.fromCharCode(92);
const [report, threshold = '15'] = process.argv.slice(2);
if (!report) {
  console.error('usage: node scripts/slow-files.mjs <vitest-json-report> [thresholdSeconds]');
  process.exit(2);
}

const root = fileURLToPath(new URL('..', import.meta.url));
const data = JSON.parse(readFileSync(report, 'utf8'));
const files = data.testResults
  .map((file) => ({
    path: relative(root, file.name).replaceAll(BACKSLASH, '/'),
    seconds: file.assertionResults.reduce((sum, test) => sum + (test.duration ?? 0), 0) / 1000,
  }))
  .filter((file) => file.seconds >= Number(threshold))
  .sort((a, b) => b.seconds - a.seconds);

// A path outside the project (or one that stayed absolute) never matches `exclude`, and the
// fast tier would quietly become the full suite: refuse instead.
const stray = files.filter((file) => file.path.startsWith('..') || /^[a-zA-Z]:|^\//.test(file.path));
if (stray.length > 0) {
  console.error('not project-relative paths in the report:', stray.map((file) => file.path));
  process.exit(1);
}

const target = new URL('../src/test/slowFiles.json', import.meta.url);
writeFileSync(
  target,
  JSON.stringify(
    {
      thresholdSeconds: Number(threshold),
      note: 'Left out of `npm run test:fast`; generated by scripts/slow-files.mjs. A speed hint, not a fence.',
      files: files.map((file) => file.path),
    },
    null,
    2,
  ) + '\n',
);

const total = data.testResults.reduce(
  (sum, file) => sum + file.assertionResults.reduce((s, t) => s + (t.duration ?? 0), 0) / 1000,
  0,
);
const slow = files.reduce((sum, file) => sum + file.seconds, 0);
console.log(
  `${files.length} of ${data.testResults.length} files are slow: ${slow.toFixed(0)} s of ${total.toFixed(0)} s of test time.`,
);
