import { describe, expect, it } from 'vitest';
import { usersCount } from './grantTexts';

// mod-019 design § 5: the count's plural forms, 1 пользователь, 2-4 пользователя, 0 and 5+ пользователей.
describe('usersCount', () => {
  it.each([
    [0, '0 пользователей'],
    [1, '1 пользователь'],
    [2, '2 пользователя'],
    [4, '4 пользователя'],
    [5, '5 пользователей'],
    [11, '11 пользователей'],
    [12, '12 пользователей'],
    [14, '14 пользователей'],
    [21, '21 пользователь'],
    [22, '22 пользователя'],
    [25, '25 пользователей'],
    [101, '101 пользователь'],
    [111, '111 пользователей'],
    [112, '112 пользователей'],
    [200, '200 пользователей'],
  ])('%i reads «%s»', (count, text) => {
    expect(usersCount(count)).toBe(text);
  });
});
