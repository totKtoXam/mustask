/**
 * Два текста: «изменён» и «уже является умолчанием, no-op».
 * `PUT /languages/default` отвечает одинаковым `200` в обоих случаях
 * (ответ никогда не говорит, действительно ли что-то изменилось), так что выбор текста — лучшее, что может сделать
 * клиент сам: был ли назначаемый язык уже флагом умолчания в том, что
 * вызывающий знал на момент прихода ответа. Вынесено в отдельный модуль
 * (а не осталось внутри `LanguagesRegistryPage.tsx`), чтобы ветка no-op —
 * обязательный сценарий, достижимый через интерфейс только настоящей гонкой
 * между клиентами (кнопка, открывающая диалог, скрыта на уже default-строке),
 * — получила прямой тест, не заглядывая в замыкание `handleAssigned`.
 *
 * Честная оговорка (не устранима в рамках текущего контракта): функция
 * читает не «то, что вызывающий знал *до* отправки запроса» —
 * `previousDefaultCode` приходит не оттуда: `LanguagesRegistryPage.tsx`'s `handleAssigned` берёт его из `query.data`,
 * т.е. из собственного кэша клиента **на момент прихода ответа**, который
 * фоновый refetch мог сдвинуть, пока диалог был открыт). Из этого следуют
 * две разные гонки, а не одна: (a) другой администратор назначает тот же
 * язык умолчанием в окне между последним запросом этого клиента и
 * подтверждением диалога этим администратором — `previousDefaultCode`
 * устарел, и функция сообщает «изменён», хотя улетающий запрос сам по себе
 * no-op на сервере; (b) прежний умолчательный язык просто не попал на
 * загруженную страницу (например, под фильтром «По умолчанию = Нет») —
 * `previousDefaultCode` равен `undefined`, и функция тоже сообщает
 * «изменён», что там как раз верно. Итоговое состояние на экране верно в
 * любом случае (назначаемый язык действительно стал умолчанием) — ошибиться
 * может только выбор, какую из двух готовых строк показать, и только в
 * гонке (a). В ответе `PUT /languages/default` нет сигнала, которым это можно
 * закрыть, — это неизбежный побочный эффект текущего контракта.
 */
export function describeDefaultAssignment(
  assignedCode: string,
  assignedEndonym: string,
  previousDefaultCode: string | undefined,
): string {
  const alreadyDefault = previousDefaultCode === assignedCode;
  return alreadyDefault
    ? `«${assignedEndonym}» уже является языком по умолчанию.`
    : `Язык по умолчанию изменён на «${assignedEndonym}» (${assignedCode}).`;
}
