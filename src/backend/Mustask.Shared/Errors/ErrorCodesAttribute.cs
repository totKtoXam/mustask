namespace Mustask.Shared.Errors;

/// <summary>
/// Помечает класс, объявляющий коды ошибок (<c>public const string</c>
/// рядом с исключением слайса — ADR-0005, п. 5) как часть проверяемого
/// множества «кодов приложения». Минимальный явный маркер:
/// <c>tests/Mustask.Contracts.Tests</c> находит такие классы рефлексией по всем
/// сборкам <c>src/</c> и проверяет, что каждая их константа есть в каталоге
/// с обоими переводами.
/// </summary>
/// <remarks>
/// Правило отбора: переводу подлежат только коды, которые могут
/// попасть в HTTP-ответ клиенту. Код фоновой задачи, шага миграции или
/// отказа при старте (никогда не покидающий сервер) этим атрибутом не
/// помечается — его место в журнале, а не в каталоге переводов.
/// </remarks>
[AttributeUsage(AttributeTargets.Class)]
public sealed class ErrorCodesAttribute : Attribute
{
}
